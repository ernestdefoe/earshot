/*
 * Earshot's page styles, compiled to their own file and loaded with the page
 * chunk — so a forum page that is not Downloads carries none of them.
 *
 * Writes css/earshot.css and js/src/forum/stylesheet.js (the content hash the
 * loader asks for, so a browser caches each version for a year and picks up
 * the next one the moment it ships). Flarum's breakpoints are given here
 * because this file is compiled outside Flarum's own LESS pipeline; every
 * colour in it is a CSS variable, so the forum's theme still applies.
 */
import less from 'less';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const source = await readFile(new URL('../less/earshot.less', import.meta.url), 'utf8');
const { css } = await less.render(source, {
  compress: true,
  globalVars: {
    phone: '~"(max-width: 767.98px)"',
    tablet: '~"(min-width: 768px) and (max-width: 991.98px)"',
  },
});

await mkdir(new URL('../css/', import.meta.url), { recursive: true });
await writeFile(new URL('../css/earshot.css', import.meta.url), css);
const hash = createHash('sha256').update(css).digest('hex').slice(0, 12);
await writeFile(new URL('./src/forum/stylesheet.js', import.meta.url), `// Generated by build-css.mjs.\nexport default '${hash}';\n`);
console.log(`css/earshot.css ${css.length} bytes, version ${hash}`);
